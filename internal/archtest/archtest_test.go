func TestLongFiles(t *testing.T) {
	t.Parallel()

	lines := func(n int) string { return strings.Repeat("x\n", n) }

	tree := fstest.MapFS{
		"internal/a/short.go":               {Data: []byte(lines(800))},
		"internal/a/long.go":                {Data: []byte(lines(801))},
		"internal/a/long_test.go":           {Data: []byte(lines(5000))},
		"internal/a/gen.go":                 {Data: []byte("// Code generated by x DO NOT EDIT.\n" + lines(5000))},
		"internal/webui/dist/bundle.go":     {Data: []byte(lines(5000))},
		"node_modules/pkg/vendor.go":        {Data: []byte(lines(5000))},
		"internal/a/notes.md":               {Data: []byte(lines(5000))},
		"internal/b/no-trailing-newline.go": {Data: []byte(strings.TrimSuffix(lines(801), "\n"))},
	}

	got, err := archtest.LongFiles(tree, 800)
	if err != nil {
		t.Fatalf("LongFiles: %v", err)
	}

	assertViolations(t, got, []string{"internal/a/long.go", "internal/b/no-trailing-newline.go"})

	for _, v := range got {
		for _, not := range []string{"short.go", "long_test.go", "gen.go", "dist", "node_modules", "notes.md"} {
			if strings.Contains(v, not) {
				t.Fatalf("%q must not be reported: %s", not, v)
			}
		}
	}
}

func assertViolations(t *testing.T, got, want []string) {
	t.Helper()

	if len(want) == 0 {
		if len(got) != 0 {
			t.Fatalf("unexpected violations: %v", got)
		}

		return
	}

	joined := strings.Join(got, "\n")
	if joined == "" {
		t.Fatalf("no violation, want ones mentioning %v", want)
	}

	for _, w := range want {
		if !strings.Contains(joined, w) {
			t.Fatalf("no violation mentions %q: %v", w, got)
		}
	}
}
