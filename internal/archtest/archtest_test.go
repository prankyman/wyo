package archtest_test

import (
	"strings"
	"testing"
	"testing/fstest"

	"github.com/prankyman/wyo/internal/archtest"
)

func pkg(path string, imports ...string) archtest.Package {
	return archtest.Package{Path: path, Imports: imports}
}

func generated(path string, imports ...string) archtest.Package {
	return archtest.Package{Path: path, Imports: imports, Generated: true}
}

func TestGeneratedPackagesAreImportedOnlyByTheirOwners(t *testing.T) {
	t.Parallel()

	httpOwner := map[string][]string{"internal/httpapi/gen": {"internal/httpapi"}}
	fcOwners := map[string][]string{"internal/fc/api": {"internal/fc", "internal/fakes/fc"}}

	tests := []struct {
		name   string
		pkgs   []archtest.Package
		owners map[string][]string
		want   []string // each must be mentioned by a violation
	}{
		{
			name:   "the owner imports its generated package",
			pkgs:   []archtest.Package{generated("internal/httpapi/gen"), pkg("internal/httpapi", "internal/httpapi/gen")},
			owners: httpOwner,
		},
		{
			name:   "a package below the owner imports it",
			pkgs:   []archtest.Package{generated("internal/fc/api"), pkg("internal/fc/sync", "internal/fc/api")},
			owners: fcOwners,
		},
		{
			name:   "the fake of what the package describes imports it",
			pkgs:   []archtest.Package{generated("internal/fc/api"), pkg("internal/fakes/fc", "internal/fc/api")},
			owners: fcOwners,
		},
		{
			name:   "a stranger imports it",
			pkgs:   []archtest.Package{generated("internal/httpapi/gen"), pkg("internal/webui", "internal/httpapi/gen")},
			owners: httpOwner,
			want:   []string{"internal/webui", "internal/httpapi/gen"},
		},
		{
			name:   "a package whose name only begins like the owner's is a stranger",
			pkgs:   []archtest.Package{generated("internal/httpapi/gen"), pkg("internal/httpapix", "internal/httpapi/gen")},
			owners: httpOwner,
			want:   []string{"internal/httpapix"},
		},
		{
			name:   "a generated package that has no owner declared",
			pkgs:   []archtest.Package{generated("internal/other/gen")},
			owners: httpOwner,
			want:   []string{"internal/other/gen", "no owner"},
		},
		{
			name:   "an owner declared for a package that is not generated",
			pkgs:   []archtest.Package{pkg("internal/fc/api")},
			owners: fcOwners,
			want:   []string{"internal/fc/api", "not a generated package"},
		},
		{
			name:   "an owner declared for a package that does not exist",
			pkgs:   nil,
			owners: fcOwners,
			want:   []string{"internal/fc/api", "not a generated package"},
		},
	}

	for _, tc := range tests {
		t.Run(tc.name, func(t *testing.T) {
			t.Parallel()

			assertViolations(t, archtest.GeneratedOnlyByOwners(tc.pkgs, tc.owners), tc.want)
		})
	}
}

func TestFakesAreImportedOnlyByFakes(t *testing.T) {
	t.Parallel()

	tests := []struct {
		name string
		pkgs []archtest.Package
		want []string
	}{
		{name: "a fake imports its kit", pkgs: []archtest.Package{pkg("internal/fakes/wb", "internal/fakes/kit")}},
		{name: "the program that starts the fakes imports them", pkgs: []archtest.Package{pkg("cmd/wyofakes", "internal/fakes/wb")}},
		{name: "the wyo server imports a fake", pkgs: []archtest.Package{pkg("cmd/wyo", "internal/fakes/wb")}, want: []string{"cmd/wyo", "internal/fakes/wb"}},
		{name: "a package of the server imports a fake", pkgs: []archtest.Package{pkg("internal/sync", "internal/fakes/kit")}, want: []string{"internal/sync"}},
		{name: "nobody imports a fake", pkgs: []archtest.Package{pkg("internal/sync", "internal/clock")}},
	}

	for _, tc := range tests {
		t.Run(tc.name, func(t *testing.T) {
			t.Parallel()

			assertViolations(t, archtest.FakesOnlyInFakes(tc.pkgs), tc.want)
		})
	}
}

