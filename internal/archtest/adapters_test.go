func TestAnIdentifierIsFoundWhereverItIsUsedExceptWhereItIsMade(t *testing.T) {
	t.Parallel()

	tree := fstest.MapFS{
		"internal/exchange/steps.go": {Data: []byte(`package exchange
func cancel() { client.PatchV3OrdersOrderIdCancelWithResponse(ctx, 1) }`)},
		"internal/exchange/steps_test.go": {Data: []byte(`package exchange_test
func TestX() { orders.PatchV3OrdersOrderIdCancel(1) }`)},
		"internal/marketplace/alpha/orders.go": {Data: []byte(`package alpha
func request() { orders.NewPatchV3OrdersOrderIdCancelRequest(server, 1) }`)},
		"internal/marketplace/alpha/api/orders.gen.go": {Data: []byte(`// Code generated by x DO NOT EDIT.
package api
func (c *Client) PatchV3OrdersOrderIdCancel() {}`)},
		"internal/marketplace/alpha/notes.go": {Data: []byte(`package alpha
// PatchV3OrdersOrderIdCancel is never called.
const name = "PatchV3OrdersOrderIdCancel"`)},
		"internal/marketplace/alpha/other.go": {Data: []byte(`package alpha
func fine() { orders.GetV3OrdersNew() }`)},
		"node_modules/pkg/vendor.go": {Data: []byte(`package pkg
func x() { PatchV3OrdersOrderIdCancel() }`)},
	}

	got, err := archtest.IdentifiersUsedOutside(tree, []string{"PatchV3OrdersOrderIdCancel"}, "internal/marketplace/alpha/api")
	if err != nil {
		t.Fatalf("IdentifiersUsedOutside: %v", err)
	}

	assertViolations(t, got, []string{"internal/exchange/steps.go:2", "internal/exchange/steps_test.go:2", "internal/marketplace/alpha/orders.go:2"})

	if len(got) != 3 {
		t.Fatalf("violations %v; want the three uses only", got)
	}
}

func TestEveryFolderRightBelowTheMarketplaceContractIsAnAdapterButTheContractSuite(t *testing.T) {
	t.Parallel()

	tree := fstest.MapFS{
		"internal/marketplace/alpha/alpha.go":       {Data: []byte("package alpha")},
		"internal/marketplace/beta/api/api.go":      {Data: []byte("package api")},
		"internal/marketplace/contracttest/c.go":    {Data: []byte("package contracttest")},
		"internal/marketplace/registry.go":          {Data: []byte("package marketplace")},
		"internal/testkit/memadapter/memadapter.go": {Data: []byte("package memadapter")},
	}

	got, err := archtest.AdapterCodes(tree)
	if err != nil || !reflect.DeepEqual(got, []string{"alpha", "beta"}) {
		t.Fatalf("AdapterCodes = %v, %v; want alpha and beta", got, err)
	}

	none, err := archtest.AdapterCodes(fstest.MapFS{})
	if err != nil || len(none) != 0 {
		t.Fatalf("a tree with no marketplace folder: %v, %v", none, err)
	}
}

func TestAMarketplaceIsNamedInNoneOfTheFoldersThatMustNotKnowOne(t *testing.T) {
	t.Parallel()

	tree := fstest.MapFS{
		"internal/exchange/steps.go":           {Data: []byte("package exchange // a call to Alpha")},
		"internal/exchange/other.go":           {Data: []byte("package exchange // the host is beta.example")},
		"internal/exchange/alphabet.go":        {Data: []byte("package exchange // alphabet is not the name")},
		"internal/fulfilment/client.go":        {Data: []byte("package fulfilment // no name here")},
		"internal/fulfilment/client_test.go":   {Data: []byte("package fulfilment_test // a test may name alpha")},
		"internal/fulfilment/fcapi/api.gen.go": {Data: []byte("// Code generated by x DO NOT EDIT.\npackage fcapi // alpha")},
		"internal/sync/caller.go":              {Data: []byte("package sync // outside the folders: alpha")},
	}

	got, err := archtest.NamedNowhereIn(tree, []string{"alpha", "beta"}, []string{"internal/exchange", "internal/fulfilment", "internal/handover"})
	if err != nil {
		t.Fatalf("NamedNowhereIn: %v", err)
	}

	assertViolations(t, got, []string{"internal/exchange/steps.go", "internal/exchange/other.go"})

	if len(got) != 2 {
		t.Fatalf("violations %v; want the two files only (a folder that is not there holds nothing)", got)
	}
}
