func TestAnAdapterImportsNoOtherAdapterAndNoWayOut(t *testing.T) {
	t.Parallel()

	tests := []struct {
		name string
		pkgs []archtest.Package
		want []string
	}{
		{name: "an adapter imports the contract and its own generated client", pkgs: []archtest.Package{
			pkg("internal/marketplace/alpha", "internal/marketplace", "internal/marketplace/alpha/api"),
		}},
		{name: "an adapter imports another", pkgs: []archtest.Package{
			pkg("internal/marketplace/alpha", "internal/marketplace/beta"),
		}, want: []string{"internal/marketplace/alpha", "internal/marketplace/beta"}},
		{name: "a package below an adapter imports another adapter's client", pkgs: []archtest.Package{
			pkg("internal/marketplace/alpha/parse", "internal/marketplace/beta/api"),
		}, want: []string{"internal/marketplace/alpha/parse"}},
		{name: "an adapter makes its own client", pkgs: []archtest.Package{
			pkg("internal/marketplace/alpha", "internal/outbound"),
		}, want: []string{"internal/outbound"}},
		{name: "an adapter reaches for the engine", pkgs: []archtest.Package{
			pkg("internal/marketplace/alpha", "internal/sync"),
		}, want: []string{"internal/sync"}},
		{name: "the contract suite is no adapter", pkgs: []archtest.Package{
			pkg("internal/marketplace/contracttest", "internal/marketplace"),
		}},
	}

	for _, tc := range tests {
		t.Run(tc.name, func(t *testing.T) {
			t.Parallel()

			assertViolations(t, archtest.AdaptersStandAlone(tc.pkgs), tc.want)
		})
	}
}

func TestAMarketplaceIsNamedOnlyWhereItMayBe(t *testing.T) {
	t.Parallel()

	tree := fstest.MapFS{
		"internal/marketplace/alpha/alpha.go":  {Data: []byte("package alpha // the Alpha marketplace")},
		"internal/fakes/alpha/fake.go":         {Data: []byte("package alpha // the fake Alpha")},
		"internal/sync/caller.go":              {Data: []byte("package sync // a call to ALPHA")},
		"internal/sync/caller_test.go":         {Data: []byte("package sync_test // a test may name alpha")},
		"internal/store/migrations/0009.sql":   {Data: []byte("-- alpha's orders")},
		"internal/httpapi/gen/server.gen.go":   {Data: []byte("// Code generated by x DO NOT EDIT.\npackage gen // alpha")},
		"internal/marketplace/marketplace.go":  {Data: []byte("package marketplace // no name here")},
		"internal/sync/notes.md":               {Data: []byte("alpha")},
		"internal/marketplace/alphabet/abc.go": {Data: []byte("package alphabet // alphabet is not the name")},
	}

	got, err := archtest.NamedOnlyIn(tree, "alpha", []string{"internal/marketplace/alpha", "internal/fakes"})
	if err != nil {
		t.Fatalf("NamedOnlyIn: %v", err)
	}

	assertViolations(t, got, []string{"internal/sync/caller.go", "internal/store/migrations/0009.sql"})

	if len(got) != 2 {
		t.Fatalf("violations %v; want only the two files", got)
	}
}

func TestAnAdaptersGeneratedClientIsAlwaysBuiltOnTheEnginesConn(t *testing.T) {
	t.Parallel()

	good := `package alpha
func client(conn marketplace.Conn) { api.NewClientWithResponses(origin, api.WithHTTPClient(conn.Doer)) }`
	bad := `package alpha
func client() { api.NewClientWithResponses(origin) }
func other() { api.NewClient(origin, api.WithRequestEditorFn(edit)) }`

	tree := fstest.MapFS{
		"internal/marketplace/alpha/good.go":      {Data: []byte(good)},
		"internal/marketplace/alpha/bad.go":       {Data: []byte(bad)},
		"internal/marketplace/alpha/bad_test.go":  {Data: []byte(bad)},
		"internal/marketplace/alpha/api/x.gen.go": {Data: []byte("// Code generated by x DO NOT EDIT.\n" + bad)},
	}

	got, err := archtest.ClientsOnTheConn(tree, "internal/marketplace")
	if err != nil {
		t.Fatalf("ClientsOnTheConn: %v", err)
	}

	assertViolations(t, got, []string{"internal/marketplace/alpha/bad.go:2", "internal/marketplace/alpha/bad.go:3"})

	if len(got) != 2 {
		t.Fatalf("violations %v; want the two calls of bad.go only", got)
	}
}

