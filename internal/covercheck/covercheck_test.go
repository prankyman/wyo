package covercheck_test

import (
	"bytes"
	"strconv"
	"strings"
	"testing"
	"testing/fstest"

	"github.com/prankyman/wyo/internal/covercheck"
)

const modulePath = "github.com/prankyman/wyo"

// profile builds the text of a coverage profile from lines "file start,end statements count".
func profile(lines ...string) string {
	return "mode: atomic\n" + strings.Join(lines, "\n") + "\n"
}

func block(file string, n, stmts, count int) string {
	return modulePath + "/" + file + ":" + strconv.Itoa(n) + ".1," + strconv.Itoa(n) + ".20 " + strconv.Itoa(stmts) + " " + strconv.Itoa(count)
}

func parse(t *testing.T, text string) covercheck.Profile {
	t.Helper()

	p, err := covercheck.ParseProfile(strings.NewReader(text))
	if err != nil {
		t.Fatalf("ParseProfile: %v", err)
	}

	return p
}

func sourceTree() fstest.MapFS {
	return fstest.MapFS{
		"internal/a/a.go":       {Data: []byte("package a\n")},
		"internal/b/b.go":       {Data: []byte("package b\n")},
		"internal/gen/gen.go":   {Data: []byte("// Code generated by a tool version 1.2.3 DO NOT EDIT.\n\npackage gen\n")},
		"internal/late/late.go": {Data: []byte("package late\n\n// Code generated by hand-waving DO NOT EDIT.\n")},
		"cmd/x/main.go":         {Data: []byte("package main\n")},
	}
}

func rules() covercheck.Rules {
	return covercheck.Rules{Threshold: 80, ModulePath: modulePath, Root: sourceTree()}
}

func TestParseProfile(t *testing.T) {
	t.Parallel()

	tests := []struct {
		name    string
		text    string
		wantErr string
	}{
		{name: "a good profile", text: profile(block("internal/a/a.go", 1, 3, 1))},
		{name: "an empty profile is a profile without blocks", text: "mode: atomic\n"},
		{name: "no mode line", text: block("internal/a/a.go", 1, 3, 1) + "\n", wantErr: "mode"},
		{name: "a line that is not a block", text: "mode: set\nnonsense\n", wantErr: "line 2"},
		{name: "a count that is not a number", text: "mode: set\n" + modulePath + "/a.go:1.1,2.2 1 many\n", wantErr: "line 2"},
		{name: "a statement count that is not a number", text: "mode: set\n" + modulePath + "/a.go:1.1,2.2 x 1\n", wantErr: "line 2"},
		{name: "an empty text", text: "", wantErr: "empty"},
	}

	for _, tc := range tests {
		t.Run(tc.name, func(t *testing.T) {
			t.Parallel()

			_, err := covercheck.ParseProfile(strings.NewReader(tc.text))

			if tc.wantErr == "" {
				if err != nil {
					t.Fatalf("unexpected error: %v", err)
				}

				return
			}

			if err == nil || !strings.Contains(err.Error(), tc.wantErr) {
				t.Fatalf("error %v, want one mentioning %q", err, tc.wantErr)
			}
		})
	}
}

func TestEvaluate(t *testing.T) {
	t.Parallel()

	tests := []struct {
		name         string
		profile      string
		rules        func(r covercheck.Rules) covercheck.Rules
		wantFailures []string // each must appear in some failure
		wantErr      string
		wantSkipped  []string // generated or excluded files
	}{
		{
			name: "every file above the floor passes",
			profile: profile(
				block("internal/a/a.go", 1, 9, 1), block("internal/a/a.go", 2, 1, 0), // 90 %
				block("internal/b/b.go", 1, 4, 3), // 100 %
			),
		},
		{
			name: "a file exactly at the floor passes",
			profile: profile(
				block("internal/a/a.go", 1, 4, 1), block("internal/a/a.go", 2, 1, 0), // 80 %
			),
		},
		{
			name: "one file under the floor fails and is named, while the whole stays above it",
			profile: profile(
				block("internal/a/a.go", 1, 100, 1),                                  // 100 %
				block("internal/b/b.go", 1, 7, 1), block("internal/b/b.go", 2, 3, 0), // 70 %
			),
			wantFailures: []string{"internal/b/b.go"},
		},
		{
			name: "the whole under the floor fails too",
			profile: profile(
				block("internal/a/a.go", 1, 1, 1), block("internal/a/a.go", 2, 9, 0), // 10 %
			),
			wantFailures: []string{"whole", "internal/a/a.go"},
		},
		{
			name: "a generated file at 0 % is left out",
			profile: profile(
				block("internal/a/a.go", 1, 5, 1),
				block("internal/gen/gen.go", 1, 500, 0),
			),
			wantSkipped: []string{"internal/gen/gen.go"},
		},
		{
			name: "a generated mark after the first line of code does not count",
			profile: profile(
				block("internal/a/a.go", 1, 5, 1),
				block("internal/late/late.go", 1, 10, 0),
			),
			wantFailures: []string{"internal/late/late.go"},
		},
		{
			name: "an excluded file with a reason is left out",
			profile: profile(
				block("internal/a/a.go", 1, 5, 1),
				block("cmd/x/main.go", 1, 3, 0),
			),
			rules: func(r covercheck.Rules) covercheck.Rules {
				r.Exclusions = []covercheck.Exclusion{{File: "cmd/x/main.go", Reason: "process wiring, proved by a process test"}}

				return r
			},
			wantSkipped: []string{"cmd/x/main.go"},
		},
		{
			name: "an exclusion without a reason is an error",
			profile: profile(
				block("internal/a/a.go", 1, 5, 1),
				block("cmd/x/main.go", 1, 3, 0),
			),
			rules: func(r covercheck.Rules) covercheck.Rules {
				r.Exclusions = []covercheck.Exclusion{{File: "cmd/x/main.go", Reason: "  "}}

				return r
			},
			wantErr: "reason",
		},
		{
			name:    "an exclusion of a file that does not exist is an error",
			profile: profile(block("internal/a/a.go", 1, 5, 1)),
			rules: func(r covercheck.Rules) covercheck.Rules {
				r.Exclusions = []covercheck.Exclusion{{File: "cmd/gone/main.go", Reason: "was here"}}

				return r
			},
			wantErr: "cmd/gone/main.go",
		},
		{
			name:    "a file of the profile that is not on disk is an error",
			profile: profile(block("internal/missing/missing.go", 1, 5, 1)),
			wantErr: "internal/missing/missing.go",
		},
		{
			name:    "a file of another module is an error",
			profile: profile("example.com/other/x.go:1.1,2.2 1 1"),
			wantErr: "example.com/other/x.go",
		},
		{
			name:    "a profile without statements has nothing to measure",
			profile: "mode: atomic\n",
			wantErr: "no statements",
		},
	}

	for _, tc := range tests {
		t.Run(tc.name, func(t *testing.T) {
			t.Parallel()

			r := rules()
			if tc.rules != nil {
				r = tc.rules(r)
			}

			report, err := covercheck.Evaluate(parse(t, tc.profile), r)

			if tc.wantErr != "" {
				if err == nil || !strings.Contains(err.Error(), tc.wantErr) {
					t.Fatalf("error %v, want one mentioning %q", err, tc.wantErr)
				}

				return
			}

			if err != nil {
				t.Fatalf("unexpected error: %v", err)
			}

			if len(tc.wantFailures) == 0 && len(report.Failures) != 0 {
				t.Fatalf("unexpected failures: %v", report.Failures)
			}

			for _, want := range tc.wantFailures {
				found := false

				for _, f := range report.Failures {
					found = found || strings.Contains(f, want)
				}

				if !found {
					t.Fatalf("no failure mentions %q: %v", want, report.Failures)
				}
			}

			for _, want := range tc.wantSkipped {
				found := false

				for _, f := range report.Skipped {
					found = found || strings.Contains(f, want)
				}

				if !found {
					t.Fatalf("%q is not listed as skipped: %v", want, report.Skipped)
				}
			}
		})
	}
}

func TestMergeCountsABlockOnceAndCoversItWhenEitherRunCoveredIt(t *testing.T) {
	t.Parallel()

	release := parse(t, profile(block("internal/a/a.go", 1, 10, 1), block("internal/a/a.go", 2, 10, 0)))
	tagged := parse(t, profile(block("internal/a/a.go", 1, 10, 0), block("internal/a/a.go", 2, 10, 4)))

	report, err := covercheck.Evaluate(covercheck.Merge(release, tagged), rules())
	if err != nil {
		t.Fatalf("Evaluate: %v", err)
	}

	if report.Total.Total != 20 || report.Total.Covered != 20 {
		t.Fatalf("total %+v: each block counts once, covered when either run covered it", report.Total)
	}
}

func TestReportWriteSaysTheFiguresAndTheFilesUnderTheFloor(t *testing.T) {
	t.Parallel()

	report, err := covercheck.Evaluate(parse(t, profile(
		block("internal/a/a.go", 1, 9, 1),
		block("internal/b/b.go", 1, 1, 1), block("internal/b/b.go", 2, 4, 0),
		block("internal/gen/gen.go", 1, 50, 0),
	)), rules())
	if err != nil {
		t.Fatalf("Evaluate: %v", err)
	}

	var out bytes.Buffer

	report.Write(&out)

	for _, want := range []string{"80%", "internal/b/b.go", "20.0%", "internal/gen/gen.go", "skipped"} {
		if !strings.Contains(out.String(), want) {
			t.Fatalf("the report does not mention %q:\n%s", want, out.String())
		}
	}
}

func TestReportWriteForAPassingRun(t *testing.T) {
	t.Parallel()

	report, err := covercheck.Evaluate(parse(t, profile(block("internal/a/a.go", 1, 9, 1))), rules())
	if err != nil {
		t.Fatalf("Evaluate: %v", err)
	}

	var out bytes.Buffer

	report.Write(&out)

	if strings.Contains(out.String(), "below") || !strings.Contains(out.String(), "100.0%") {
		t.Fatalf("unexpected report:\n%s", out.String())
	}
}
